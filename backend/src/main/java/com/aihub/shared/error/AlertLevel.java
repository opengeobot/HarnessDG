package com.aihub.shared.error;

/**
 * 错误码告警等级。
 *
 * <p>用于可观测性管线判断某类错误是否需要触发告警以及告警优先级。
 */
public enum AlertLevel {

    /** 无需告警，通常为可预期的客户端错误。 */
    NONE,

    /** 关注级别，记录指标但一般不打扰值班。 */
    INFO,

    /** 告警级别，达到阈值需通知。 */
    WARN,

    /** 严重级别，需立即介入。 */
    CRITICAL
}
